-- No existing patient is removed or rewritten; map only exact/recognized case-insensitive values.
with matched as (
 select p.id, s.id sid,
   (select b.id from public.breed_catalog b where b.species_id=s.id
       and lower(b.label)=lower(btrim(p.breed)) limit 1) bid
 from public.pets p left join public.species_catalog s
   on lower(btrim(p.species))=lower(s.label)
   or (lower(btrim(p.species)) in ('cow','cows','cattle') and s.id='cattle')
   or (lower(btrim(p.species)) in ('canine','dogs') and s.id='dog')
   or (lower(btrim(p.species)) in ('feline','cats') and s.id='cat')
 where p.species_id is null
)
update public.pets p
set species_id=m.sid, breed_id=m.bid,
  taxonomy_review_needed=(m.sid is null or
      (nullif(btrim(coalesce(p.breed,'')),'') is not null and m.bid is null))
from matched m where p.id=m.id;

